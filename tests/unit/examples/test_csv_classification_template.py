def test_metric_counts_a_missing_prediction_wrong_and_ignores_an_unknown_id(
    data_dir: Path,
) -> None:
    """Defect: the metric's denominator follows the predictions instead of the
    validation rows, so dropping a hard row raises the score, or a stray ID
    changes it. Ten rows per class: one missing class-0 row gives recall 0.9."""
    with run_registration_scope():
        composition = compose_run_task_bindings(str(MANIFEST))
        path = composition.task_data_path
        with bind_run_task_composition(composition, physical_data_root=str(data_dir)):
            scope = path.build_eval_scope(FULL)
            truth = path.labels_by_sample_id(scope, str(data_dir))
            dropped = next(sample for sample, label in truth.items() if label == 0)

            def score(payload: dict[str, int]) -> float:
                return composition.metric.evaluate(
                    {0: str(data_dir / "validation.csv")},
                    evaluation_payload=payload,
                    task_scope=scope,
                    data_dir=str(data_dir),
                ).scalar

            missing = {k: v for k, v in truth.items() if k != dropped}
            assert score(missing) == pytest.approx((0.9 + 1.0 + 1.0) / 3)
            assert score({**truth, "not_a_validation_row": 2}) == pytest.approx(1.0)


def test_inference_deliverable_metric_and_health_on_a_real_csv(
    data_dir: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Defect: truth is not read from the data folder, outputs are paired with
    the wrong rows, or Health is detached from the deliverable.

    The production inference unit writes predictions for two controls. A
    model that always predicts class 0 has balanced accuracy exactly 1/3 and
    must fail the blocking gate (invalidating the round) and the recording
    gate (recorded, not invalidating). A model predicting the true class (the
    generated label equals the rounded first feature mean) scores 1.0 and
    passes both. The Health coverage check required before a Health-enabled
    attempt accepts the evaluation scope.
    """
    import torch

    from execute_tools.generic_inference import run_generic_inference
    from execute_tools.health_checks import runner
    from execute_tools.health_checks.config import load_composed_health_config
    from execute_tools.health_checks.schemas import CheckVerdict, HealthCheckContext
    from execute_tools.task_data_path import TaskHealthCoverageError
    from nodes.ml_hyperparameter_tune_agent.health_coverage import (
        validate_attempt_health_coverage,
    )

    class ConstantClass(torch.nn.Module):
        def forward(self, x: torch.Tensor) -> torch.Tensor:
            logits = torch.zeros((len(x), len(CLASSES)), dtype=x.dtype)
            logits[:, 0] = 1.0
            return logits

    class NearestMean(torch.nn.Module):
        def forward(self, x: torch.Tensor) -> torch.Tensor:
            centres = torch.arange(len(CLASSES), dtype=x.dtype)
            return -((x.mean(dim=1, keepdim=True) - centres) ** 2)

    health_config, _task_config, _plugins = load_composed_health_config(
        None, str(TEMPLATE / "declared/task_health.yaml")
    )
    monkeypatch.setattr(runner, "load_health_gates_config", lambda *a, **k: health_config)
    with run_registration_scope():
        composition = compose_run_task_bindings(str(MANIFEST))
        path = composition.task_data_path
        with bind_run_task_composition(composition, physical_data_root=str(data_dir)):
            scope = path.build_eval_scope(FULL)
            coverage = validate_attempt_health_coverage(
                data_path=path,
                evaluation_scope=scope,
                round_kind="formal",
                health_binding=composition.task_health_binding,
                composed=True,
                health_enabled=True,
            )
            assert coverage is not None and coverage.covered

            def coverage_with(files: tuple[int, ...]):
                return validate_attempt_health_coverage(
                    data_path=path,
                    evaluation_scope=scope,
                    round_kind="formal",
                    health_binding=composition.task_health_binding,
                    health_gate_files=files,
                    composed=True,
                    health_enabled=True,
                )

            assert coverage_with((1,)).covered
            for unsupported in ((0,), (0, 1)):
                with pytest.raises(TaskHealthCoverageError, match="health_gate_files"):
                    coverage_with(unsupported)

            def run(model: torch.nn.Module, exp_id: str):
                identity = {"exp_id": exp_id, "run_name": "template", "model_type": "control"}
                out = tmp_path / exp_id
                outcome = run_generic_inference(
                    data_path=path,
                    task_scope=scope,
                    model=model,
                    device=torch.device("cpu"),
                    data_dir=str(data_dir),
                    batch_size=7,
                    write_request=DeliverableWriteRequest(output_dir=str(out), **identity),
                )
                assert outcome.samples == VALIDATION_ROWS
                read = EvaluationReadRequest(deliverable_dir=str(out), **identity)
                payload = path.read_evaluation_payload(read)
                score = composition.metric.evaluate(
                    {0: str(out / outcome.deliverable_name)},
                    evaluation_payload=payload,
                    task_scope=scope,
                    data_dir=str(data_dir),
                ).scalar
                gates = {
                    gate: runner.evaluate_gate(
                        gate,
                        HealthCheckContext(
                            model_name="control",
                            run_name="template",
                            round_index=1,
                            evaluation_payload_fn=lambda: path.read_evaluation_payload(read),
                        ),
                    )
                    for gate in ("predicts_more_than_one_class", "dominant_class_fraction")
                }
                return score, gates

            constant_score, constant = run(ConstantClass(), "constant")
            right_score, right = run(NearestMean(), "right")

    assert constant_score == pytest.approx(1 / 3)
    assert right_score == pytest.approx(1.0)
    blocking, recording = (
        constant["predicts_more_than_one_class"],
        constant["dominant_class_fraction"],
    )
    assert blocking.check_results[0].verdict is CheckVerdict.FAILED
    assert blocking.action.value == "invalidate_round"
    assert recording.check_results[0].verdict is CheckVerdict.FAILED
    assert recording.action.value == "continue"
    assert all(gate.passed for gate in right.values())


@pytest.mark.parametrize(
    ("train_portion", "max_samples", "rows"), [(0.5, None, 30), (None, 10, 10)]
)
def test_guardrail_step_pricing_counts_a_sampled_template_epoch(
    data_dir: Path, train_portion, max_samples, rows: int
) -> None:
    """Defect: the tuner's step guardrail materializes the training dataset
    without an epoch seed; the template refuses that, and the guardrail's
    non-fatal handler silently stops pricing ``max_steps_per_attempt``.
    Requires the framework fix in PR #1170 (explicit row-count epoch seed)."""
    from execute_tools.training_batches import optimizer_steps_for_rows
    from execute_tools.workload_resolvers import resolve_task_scope_training_workload

    with run_registration_scope():
        composition = compose_run_task_bindings(str(MANIFEST))
        with bind_run_task_composition(composition, physical_data_root=str(data_dir)):
            workload = resolve_task_scope_training_workload(
                composition.task_data_path.build_training_scope(FULL),
                data_dir=str(data_dir),
                batch_size=4,
                train_portion=train_portion,
                epochs=2,
                max_samples=max_samples,
            )
    assert workload.detail["samples_per_epoch"] == rows
    assert workload.unit_count == optimizer_steps_for_rows(rows, 4, drop_last=True) * 2
