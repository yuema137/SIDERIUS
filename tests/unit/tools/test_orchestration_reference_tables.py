"""The orchestrator-toolkit reference tables must match the installed code.

The toolkit payload tells a research agent which fields each node accepts,
which CLI options exist with which defaults, and how to construct each agent.
Synced by hand, those tables fell about 40 fields and 11 options behind source
and kept stale provider defaults (#1531, #1535). They are now generated by
``tools.orchestration_setup.reference_tables``; these tests fail when a
committed table differs from what source renders today.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pytest

from tools.orchestration_setup import reference_tables

REPO_ROOT = Path(__file__).resolve().parents[3]
REFERENCES = REPO_ROOT / reference_tables.PAYLOAD_REFERENCES


def test_committed_toolkit_tables_match_source() -> None:
    """Defects caught: a node schema gains, loses, renames or re-types a
    field, changes a default or description; a CLI gains or loses an option
    or changes its default, choices or help; an agent constructor changes its
    signature or a provider/model default; and none of the toolkit tables
    follows. The check runs in an isolated child with empty plugin
    directories, exactly like ``--check``. To fix: run
    ``python -m tools.orchestration_setup.reference_tables --write``."""
    assert reference_tables.main(["--check"]) == 0, (
        "orchestrator-toolkit reference tables drifted from source; run "
        "`python -m tools.orchestration_setup.reference_tables --write`"
    )


@pytest.mark.parametrize(
    ("folder", "kind"), [("schemas", "schema"), ("cli", "cli"), ("agents", "constructor")]
)
def test_every_reference_page_keeps_its_generated_region(folder: str, kind: str) -> None:
    """Defect caught: a page's markers are deleted or renamed, so the check
    above silently stops covering that page and it can drift again."""
    pages = sorted((REFERENCES / folder).glob("*.md"))
    assert pages, f"no toolkit pages under {folder}/"
    missing = [
        page.name
        for page in pages
        if f"<!-- generated: {kind} " not in page.read_text(encoding="utf-8")
    ]
    assert not missing, f"{folder}/ pages without a generated {kind} region: {missing}"


def test_a_main_that_never_parses_is_refused(monkeypatch: pytest.MonkeyPatch) -> None:
    """Defect caught: a node ``main()`` stops building its parser before
    returning, and the generator renders an empty CLI table instead of
    failing."""

    class Module:
        @staticmethod
        def main() -> None:
            argparse.ArgumentParser()

    monkeypatch.setattr(reference_tables.importlib, "import_module", lambda _name: Module)
    with pytest.raises(RuntimeError, match="returned without parsing"):
        reference_tables.capture_parser("fake.module")


def test_a_main_using_parse_known_args_is_captured_not_executed(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Defect caught: a node ``main()`` switches to ``parse_known_args`` and
    the generator runs the node body (with the generator's own argv) instead
    of stopping at the parser."""
    ran: list[str] = []

    class Module:
        @staticmethod
        def main() -> None:
            parser = argparse.ArgumentParser()
            parser.add_argument("--flag")
            parser.parse_known_args()
            ran.append("node body")

    monkeypatch.setattr(reference_tables.importlib, "import_module", lambda _name: Module)
    parser = reference_tables.capture_parser("fake.module")
    assert [a.dest for a in parser._actions if a.option_strings != ["-h", "--help"]] == ["flag"]
    assert not ran, "the node body executed after parse_known_args"
