class TestThePydanticVocabularyTheSuppressionCouplesTo:
    """``_rejection_is_only_the_undeclared_segmentation_size`` reads Pydantic's
    error vocabulary directly — ``type == "missing"`` and a bare
    ``loc == ("segmentation_size",)``. That is a coupling to a third-party
    contract, and it should be visible to whoever next upgrades Pydantic.

    The coupling is SAFE by construction: every unrecognised shape makes the
    predicate return ``False``, i.e. "report this rejection". A vocabulary
    change therefore produces a false REJECTION — a loud, actionable repair
    message — never a silent pass. These tests pin the vocabulary so the
    upgrade is caught here rather than as a confusing implementor failure.
    """

    def test_a_missing_required_field_reports_type_missing_at_a_bare_loc(self):
        """DEFECT THIS TEST ALONE CATCHES

            A Pydantic upgrade renaming ``"missing"`` or nesting ``loc``.
            Nothing else in the suite asserts this vocabulary, and production
            would degrade quietly into "never suppress" — every undeclared
            candidate would then burn its whole repair budget on the
            unsatisfiable instruction the suppression exists to avoid.

        HOW IT FAILS WHEN THE BEHAVIOUR REGRESSES

            The error ``type`` or ``loc`` assertion names the new shape, and
            the predicate assertion shows production no longer recognises it.
        """
        from pydantic import BaseModel, Field, ValidationError

        class _Probe(BaseModel):
            segmentation_size: int = Field(ge=1)

        with pytest.raises(ValidationError) as excinfo:
            _Probe()

        details = excinfo.value.errors()
        assert len(details) == 1
        assert details[0]["type"] == "missing"
        assert tuple(details[0]["loc"]) == ("segmentation_size",)

        # ...and production reads that shape correctly, asked through its own
        # entry point rather than by re-deriving the comparison here.
        assert _impl._rejection_is_only_the_undeclared_segmentation_size(excinfo.value, {}) is True

    def test_an_unrecognised_exception_shape_fails_CLOSED(self):
        """DEFECT THIS TEST ALONE CATCHES

            The predicate's fallbacks being flipped to ``True`` — "if I can't
            tell, assume it's the benign one". That is the difference between
            a suppression that hides exactly one unactionable error and one
            that silences the Phase-B.2a gate whenever it is confused.

        HOW IT FAILS WHEN THE BEHAVIOUR REGRESSES

            Any of these returns ``True``, meaning a rejection production
            could not classify would be discarded rather than reported.
        """

        class _ErrorsRaises(Exception):
            def errors(self):
                raise RuntimeError("errors() itself is broken")

        # not a Pydantic error at all
        assert (
            _impl._rejection_is_only_the_undeclared_segmentation_size(RuntimeError("x"), {})
            is False
        )
        # has errors(), but calling it blows up
        assert (
            _impl._rejection_is_only_the_undeclared_segmentation_size(_ErrorsRaises(), {}) is False
        )

    def test_the_baseline_having_stated_the_key_is_checked_before_the_vocabulary(self):
        """DEFECT THIS TEST ALONE CATCHES

            The predicate keying on the ERROR alone. A baseline that stated
            ``segmentation_size`` and had it rejected is a real schema
            conflict — the exact class Phase B.2a exists for — and it must
            never be suppressed just because the error mentions that field.

        HOW IT FAILS WHEN THE BEHAVIOUR REGRESSES

            The assertion returns ``True`` for a baseline that plainly
            declared the key.
        """
        from pydantic import BaseModel, Field, ValidationError

        class _Probe(BaseModel):
            segmentation_size: int = Field(ge=1)

        with pytest.raises(ValidationError) as excinfo:
            _Probe()

        assert (
            _impl._rejection_is_only_the_undeclared_segmentation_size(
                excinfo.value, {"segmentation_size": 144}
            )
            is False
        )


