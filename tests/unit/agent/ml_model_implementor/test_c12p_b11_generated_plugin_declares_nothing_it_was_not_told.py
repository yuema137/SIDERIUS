"""C12-P / F-12e-G1 — the GENERATED PLUGIN declares nothing the baseline said.

THE ESCAPED CLASS, NAMED
------------------------
*The framework authors a value into an artifact that later becomes the
model's own declaration.*

B11's standing census
(``tests/unit/guardrails/test_c12p_b11_segmentation_default_census.py``) is a
SOURCE-LEVEL scan for ``<mapping>.get("segmentation_size", <int literal>)``.
It cannot own this class, and the reason is structural rather than a matter of
tuning the regex: after the repair **there is no literal left in the source to
find**. The number's whole career was to be written into generated bytes. So
the only place the property can be asserted is the ARTIFACT — assemble a
plugin, execute it, register it exactly as production does, and ask the
production resolution chain what the model declares.

That chain, end to end, is what made a framework literal permanent::

    _assemble_plugin        writes `segmentation_size: int = Field(default=N)`
    register_model_in_memory  -> PLUGIN_CONFIG_REGISTRY
    get_config_class          -> the generated class
    estimator.resolve_model_field   reads its DECLARED default
    planning._resolve_declared_segmentation_size    -> that value, never None

Because a generated class ALWAYS declared a default, the middle link could
never return ``None`` for a plugin, and the task's named refusal
(``execute_tools/tidmad_data_path.py``: *"the framework has no vocabulary for
it, so it must be declared by the caller rather than guessed here"*) — which
F-C12P-B11-2's approved repair exists to keep reachable — was defeated from
OUTSIDE the tuner. The framework's own 40000 came back to it wearing the
task's clothes.

Measured harm, for a generated non-TIDMAD candidate:
``agent/skills/training_skill/estimator.py`` prices activations as
``batch_size * 256 * segmentation_size * 4``. Pets' 144 replaced by 40000 is a
278x VRAM over-estimate, so the capacity gate rejects a perfectly feasible
architecture and burns a tuner attempt — silently, with a plausible number.

WHY THE FIXTURES ARE HAND-WRITTEN
---------------------------------
Every expectation below is a hardcoded literal (``0``, ``None``, ``144``, the
exact emitted field line). Nothing is read back from the thing under test: an
assertion like ``emitted == Model.model_fields[...].default`` compares the
artifact to itself and passes for any value, which is precisely how a
recomputation defect survives a green suite.
"""

from __future__ import annotations

import importlib

import pytest

from agent.schemas.implementor import ImplementorInput

_impl = importlib.import_module("nodes.ml_model_implementor.ml_model_implementor")
#: The DOWNSTREAM consumer of the same construction rule. ``TestOne
#: ProbeConstructionAuthority`` asserts across both nodes on purpose: the
#: property is that exactly one authority exists, and a per-node test cannot
#: express it.
_val = importlib.import_module("nodes.ml_code_validator_agent.ml_code_validator_agent")
#: A tuner-private module. Tests are deliberately exempt from the node public
#: boundary rule (``tests/unit/nodes/test_node_public_boundary.py``) precisely
#: so a reachability test like this one can assert against the real consumer.
_planning = importlib.import_module("nodes.ml_hyperparameter_tune_agent.planning")

_FIELD = "segmentation_size"

#: A minimal but REAL architecture: the assembled plugin is EXECUTED — its
#: smoke test, its own generated pytest file and the registry all run against
#: it — so it must honour the default ``classifier`` contract
#: (``[B, T] int -> [B, 256, T] float``). It deliberately does not read
#: ``config.segmentation_size``, so the declared and undeclared cases differ in
#: exactly one thing.
#:
#: ``channels`` is declared ``ge=8`` so that a baseline asking for 2 is a
#: genuine constraint violation — that is what
#: ``test_a_real_schema_rejection_is_still_reported`` needs, and a ``ge=1``
#: here would make it pass vacuously.
_CODE = {
    "extra_imports": "",
    "config_fields_code": "    channels: int = Field(default=8, ge=8)",
    "config_validators_code": "",
    "init_body": (
        "        self.emb = nn.Embedding(256, config.channels)\n"
        "        self.out = nn.Conv1d(config.channels, 256, 1)"
    ),
    "forward_body": "        return self.out(self.emb(x.long()).transpose(1, 2))",
}


def _implementor_input(model_name: str, model_config: dict) -> ImplementorInput:
    """A Pets-shaped baseline: small, non-TIDMAD, and 1-D-geometry-free."""
    return ImplementorInput(
        model_name=model_name,
        model_description="C12-P F-12e-G1 fixture candidate.",
        mathematical_definition="Embedding(256, C) -> transpose -> Conv1d(C, 256, 1). Fixture.",
        baseline_config={
            "model_config": model_config,
            # NOTE: `train_config` deliberately carries no `segmentation_size`
            # either. `TrainConfig` (`ml_models/models_format_sandbox.py`)
            # declares no such field, so the implementor's old inner fallback
            # `train_cfg.get("segmentation_size", 40000)` was dead code whose
            # only reachable arm was the 40000.
            "train_config": {"batch_size": 4, "lr": 5e-4},
        },
    )


@pytest.fixture
def registered(tmp_path):
    """Assemble, execute and register a candidate the way production does.

    Yields a ``register(model_name, model_config) -> plugin_source`` callable.
    Registration mutates three module-level dicts, so every entry is removed
    afterwards — a leaked registration would make a LATER test's
    ``get_config_class`` resolve and silently change what it proves.
    """
    from ml_models.models_format_sandbox import PLUGIN_CONFIG_REGISTRY
    from ml_models.models_sandbox import MODEL_REGISTRY
    from ml_models.plugin_loader import PLUGIN_OUTPUT_TYPE_REGISTRY, register_model_in_memory

    created: list[str] = []

    def _register(model_name: str, model_config: dict) -> str:
        src = _impl._assemble_plugin(_implementor_input(model_name, model_config), _CODE)
        path = tmp_path / f"{model_name}.py"
        path.write_text(src, encoding="utf-8")
        assert register_model_in_memory(str(path)) == model_name, (
            "the assembled plugin did not load — this test proves nothing "
            "about declarations until it does"
        )
        created.append(model_name)
        return src

    try:
        yield _register
    finally:
        for name in created:
            MODEL_REGISTRY.pop(name, None)
            PLUGIN_CONFIG_REGISTRY.pop(name, None)
            PLUGIN_OUTPUT_TYPE_REGISTRY.pop(name, None)


def _resolution_chain(model_name: str) -> tuple[int, int | None]:
    """``(resolve_model_field, _resolve_declared_segmentation_size)``.

    The two production readers, asked in the order production asks them.
    ``safety_margin=0`` is the tuner's own "nothing declares this" sentinel.
    """
    from agent.skills.training_skill.estimator import resolve_model_field

    return (
        resolve_model_field(model_name, {}, _FIELD, safety_margin=0),
        _planning._resolve_declared_segmentation_size(model_name, {}),
    )


class TestAnUndeclaredSizeStaysUndeclared:
    def test_an_omitted_size_is_not_authored_into_the_generated_declaration(self, registered):
        """DEFECT THIS TEST ALONE CATCHES

            ``_assemble_plugin`` writing a framework-chosen number into the
            generated class's own default when the baseline declared none —
            after which every downstream reader is looking at a declaration
            that no proposer, plan or task ever made. A source-level census
            structurally cannot see this, because the number ends up in
            generated bytes, not in repository source.

        HOW IT FAILS WHEN THE BEHAVIOUR REGRESSES

            Someone restores ``.get(_FIELD, 40000)`` (or any other literal) at
            the assembly site. The emitted line then reads
            ``Field(default=40000, ge=1)`` instead of ``Field(ge=1)`` and the
            first assertion names it; the resolution chain then returns 40000
            instead of ``0``/``None`` and the remaining two name it again, at
            the exact two call sites that made the number consequential.
        """
        source = registered("c12p_f12e_g1_omitted_v1", {"channels": 8})

        emitted = [ln for ln in source.splitlines() if ln.strip().startswith(f"{_FIELD}:")]
        assert emitted == ["    segmentation_size: int = Field(ge=1)"], (
            "the generated plugin declares a segmentation_size the baseline "
            f"never stated: {emitted}"
        )

        resolved, declared = _resolution_chain("c12p_f12e_g1_omitted_v1")
        assert resolved == 0, (
            "`resolve_model_field` found a declared default on a class whose "
            "baseline declared none — the framework's literal is being read "
            "back as the model's own value"
        )
        assert declared is None, (
            "the tuner resolved a segmentation size for a candidate nothing "
            "declared one for; the task's named refusal is unreachable again"
        )

    def test_the_field_still_exists_on_the_generated_class(self, registered):
        """DEFECT THIS TEST ALONE CATCHES

            "Don't author a value" implemented as "drop the field". Two
            production readers access it as an ATTRIBUTE —
            ``agent/skills/training_skill/train_engine_sandbox.py`` and
            ``agent/skills/inference_skill/inference_single.py`` — and
            ``_TEMPLATE_CONFIG_FIELDS`` still forbids the LLM to declare it,
            so a removed field would leave it declared by nobody at all.

        HOW IT FAILS WHEN THE BEHAVIOUR REGRESSES

            The template stops emitting the field and ``model_fields`` no
            longer contains it.
        """
        from ml_models.models_format_sandbox import get_config_class

        registered("c12p_f12e_g1_exists_v1", {"channels": 8})
        config_cls = get_config_class("c12p_f12e_g1_exists_v1")
        assert config_cls is not None
        assert _FIELD in config_cls.model_fields, (
            "the generated class no longer declares `segmentation_size` at "
            "all; train_engine_sandbox and inference_single read it as an "
            "attribute"
        )
        assert config_cls.model_fields[_FIELD].is_required(), (
            "an undeclared size must be REQUIRED, not optional-with-a-value: "
            "any usable default is a number the framework chose"
        )


